"use strict";
const assert = require("node:assert/strict");
const { createLobby } = require("../lobby/lobby-server");
const players = new Map();
const sent = [];
const broadcasted = [];
const send = (ws, payload) => sent.push({ to: ws.id, payload });
const broadcast = payload => broadcasted.push(payload);
const p1 = { id: "p1", name: "Host", team: "blue", ws: { id: "p1" } };
const p2 = { id: "p2", name: "Guest", team: "red", ws: { id: "p2" } };
players.set(p1.id, p1); players.set(p2.id, p2);
const starts = [];
const lobby = createLobby({ players, send, broadcast, maxPlayers: 4, minPlayers: 1, onStart: list => starts.push(list.map(p => p.id)) });
lobby.onConnect(p1);
lobby.onConnect(p2);
assert.equal(lobby.hostId, "p1", "first connected player becomes host");
assert.equal(lobby.state(p1).canStart, false, "host waits for non-host players to ready");
assert.equal(lobby.handle(p2, { type: "lobby-ready", ready: true }), true);
assert.equal(lobby.state(p1).canStart, true, "host can start when other players are ready");
assert.equal(lobby.handle(p1, { type: "lobby-start" }), true);
assert.equal(lobby.phase, "playing", "start transitions lobby into match");
assert.deepEqual(starts, [["p1", "p2"]], "start callback receives connected players");
assert.ok(broadcasted.some(m => m.type === "lobby-started"), "match start is broadcast");
lobby.handle(p2, { type: "lobby-team", team: "blue" });
assert.ok(sent.some(m => m.to === "p2" && m.payload.type === "lobby-error"), "team change is rejected after match starts");
players.delete("p1");
lobby.onDisconnect();
assert.equal(lobby.hostId, "p2", "host transfers when current host disconnects");
console.log("Lobby integration OK");
